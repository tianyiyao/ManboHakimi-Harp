if __name__ == "__main__":
    total_notes = 0
    for sid, (name, bpm, text) in SCORES.items():
        score = parse_jianpu(text, name=name, bpm=bpm, score_id=sid)
        for beat, lyric_text in LYRICS.get(sid, []):
            score.lyrics.append(LyricLine(time_ms=beat * 60000.0 / bpm,
                                          text=lyric_text))
        if not score.notes:
            raise SystemExit(f"曲目 {sid} 解析为空，检查简谱文本")
        path = OUT / f"{sid}.json"
        score.save(path)
        holds = sum(1 for n in score.notes if n.type.value == "hold")
        print(f"{path.name:<28} {len(score.notes):>3} 音符 ({holds} 长按) "
              f"{len(score.lyrics):>2} 句歌词 "
              f"{score.total_beats():>6.1f} 拍 / {score.total_ms() / 1000:>5.1f}s "
              f"BPM {bpm}")
        total_notes += len(score.notes)
    print(f"共 {len(SCORES)} 首内置曲目，{total_notes} 个音符；输出目录 {OUT}")